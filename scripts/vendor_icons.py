"""Embed the Lucide icons the app draws.

Usage: python3 scripts/vendor_icons.py <unpacked lucide-static package>
Get the package with `npm pack lucide-static --ignore-scripts` and untar it.
Writes the table to crates/errand-core/src/icons/data.rs.
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ICONS = [
    "check", "check-check", "chevron-down", "chevron-up", "circle-alert", "circle-arrow-right",
    "circle-check", "circle-question-mark", "circle-slash", "clock", "corner-down-right", "external-link",
    "folder", "layout-dashboard", "list-todo", "loader-circle", "refresh-cw", "timer", "x", "undo-2", "battery-warning",
    "chevron-left", "chevron-right", "shuffle", "users", "lock", "plus", "message-circle-question-mark", "paperclip",
]


def header(version, license_text):
    return [
        f"// Generated by scripts/vendor_icons.py from lucide-static {version}. Do not edit.",
        "// Each icon is its SVG elements on Lucide's 24-unit grid.",
        "/*",
        *license_text.splitlines(),
        "*/",
    ]


def rust_string(value):
    return '"' + str(value).replace("\\", "\\\\").replace('"', '\\"') + '"'


def rust_element(kind, attributes):
    # A missing attribute reads as zero, as SVG renderers treat it.
    def number(key):
        return repr(float(attributes.get(key) or 0))
    if kind == "path":
        return f"Path({rust_string(attributes['d'])})"
    if kind in ("circle", "ellipse"):
        if "r" in attributes:
            return f"Circle {{ cx: {number('cx')}, cy: {number('cy')}, r: {number('r')} }}"
        return f"Ellipse {{ cx: {number('cx')}, cy: {number('cy')}, rx: {number('rx')}, ry: {number('ry')} }}"
    if kind == "rect":
        rx = number("rx") if "rx" in attributes else number("ry")
        ry = number("ry") if "ry" in attributes else rx
        return f"Rect {{ x: {number('x')}, y: {number('y')}, width: {number('width')}, height: {number('height')}, rx: {rx}, ry: {ry} }}"
    if kind == "line":
        return f"Line {{ x1: {number('x1')}, y1: {number('y1')}, x2: {number('x2')}, y2: {number('y2')} }}"
    if kind in ("polyline", "polygon"):
        values = [float(part) for part in attributes["points"].replace(",", " ").split()]
        points = ", ".join(f"({x!r}, {y!r})" for x, y in zip(values[0::2], values[1::2]))
        return f"{kind.capitalize()}(&[{points}])"
    raise SystemExit(f"Unsupported Lucide element: {kind}")


def rust_table(nodes, version, license_text):
    lines = header(version, license_text) + [
        "use super::Element::{self, *};",
        "",
        "#[rustfmt::skip]",
        "pub(super) static ICONS: &[(&str, &[Element])] = &[",
    ]
    for name in ICONS:
        elements = ", ".join(rust_element(kind, attributes) for kind, attributes in nodes[name])
        lines.append(f"    ({rust_string(name)}, &[{elements}]),")
    return "\n".join(lines + ["];", ""])


def main(package):
    nodes = json.loads((package / "icon-nodes.json").read_text())
    version = json.loads((package / "package.json").read_text())["version"]
    license_text = (package / "LICENSE").read_text().strip()
    (ROOT / "crates/errand-core/src/icons/data.rs").write_text(rust_table(nodes, version, license_text))
    print(f"Embedded {len(ICONS)} Lucide {version} icons")


if __name__ == "__main__":
    main(Path(sys.argv[1]))
